import { afterEach, describe, expect, it, vi } from 'vitest'
import { factoryBatchesApi, modelIterationApi, phoneFactoryApi } from './phoneFactoryApi'
import { notifyBatchesPublished } from '@/utils/batchLifecycle'
afterEach(() => vi.unstubAllGlobals())
describe('phone factory transport contracts', () => {
  it('preserves failed preview snapshots and scopes async controls without touching phone endpoints', async () => {
    const failed = { preview_id: 'preview/a', valid: false, status: 'failed', revision: 3, job_version: 1, retryable: true, error: 'disk full', cases: [], errors: [] }
    const fetcher = vi.fn(async () => new Response(JSON.stringify(failed)))
    vi.stubGlobal('fetch', fetcher)
    expect(await modelIterationApi.evaluationPreview({ source_path: 'D:/轨迹', request_id: 'preview-request' })).toEqual(failed)
    expect(await modelIterationApi.evaluationPreviewState('preview/a', undefined, 10, 10)).toEqual(failed)
    const control = { request_id: 'control-request', expected_revision: 3 }
    await modelIterationApi.evaluationPreviewControl('preview/a', 'retry', control)
    fetcher.mockResolvedValueOnce(new Response('{"run_id":"eval/a","status":"preparing"}'))
    await modelIterationApi.retryEvaluationPreparation('eval/a', control)
    expect(fetcher.mock.calls.map(call => call[0])).toEqual(['/api/model-iter/evaluation-preview', '/api/model-iter/evaluation-previews/preview%2Fa?offset=10&limit=10', '/api/model-iter/evaluation-previews/preview%2Fa/retry', '/api/model-iter/runs/eval%2Fa/retry-preparation'])
    expect(JSON.parse(String(fetcher.mock.calls[0]?.[1]?.body))).toEqual({ source_path: 'D:/轨迹', request_id: 'preview-request' })
    expect(JSON.parse(String(fetcher.mock.calls[2]?.[1]?.body))).toEqual(control)
    expect(JSON.parse(String(fetcher.mock.calls[3]?.[1]?.body))).toEqual(control)
  })
  it('uses encoded diagnostic and grouped-case endpoints and preserves the resume identity across requests', async () => {
    const fetcher = vi.fn(async () => new Response('{"ok":true,"operation_id":"stable/request","status":"accepted"}')); vi.stubGlobal('fetch', fetcher)
    const signal = new AbortController().signal
    await phoneFactoryApi.diagnostics('run/a', signal)
    await phoneFactoryApi.casePage('run/a', { app: 'App A', phone_id: 'p/1', status: 'failed', q: '搜索', offset: 20, limit: 10 }, signal)
    await phoneFactoryApi.caseInstances('run/a', 'case/a', 'p/1', signal)
    await phoneFactoryApi.resumePreview('run/a', ['p/1'], signal)
    const body = { request_id: 'stable/request', preview_id: 'preview', selection_digest: 'digest', expected_revision: 4, confirm_unknown_phone_ids: ['p/1'] }
    await phoneFactoryApi.resumeCollection('run/a', body, signal)
    await phoneFactoryApi.resumeOperation('run/a', body.request_id, signal)
    expect(fetcher.mock.calls[0]?.[0]).toBe('/api/phone-factory/collection-runs/run%2Fa/diagnostics')
    expect(fetcher.mock.calls[1]?.[0]).toContain('offset=20&limit=10&app=App+A&phone_id=p%2F1&status=failed&q=')
    expect(fetcher.mock.calls[2]?.[0]).toBe('/api/phone-factory/collection-runs/run%2Fa/cases/case%2Fa/instances?phone_id=p%2F1')
    expect(JSON.parse(String(fetcher.mock.calls[4]?.[1]?.body))).toEqual(body)
    expect(fetcher.mock.calls[5]?.[0]).toBe('/api/phone-factory/collection-runs/run%2Fa/resume-operations/stable%2Frequest')
    for (const call of fetcher.mock.calls) expect(call[1]?.signal).toBe(signal)
  })
  it('binds resumed instance evidence to its physical execution without changing old artifact URLs', async () => {
    const fetcher = vi.fn(async () => new Response('{"ok":true}')); vi.stubGlobal('fetch', fetcher)
    await phoneFactoryApi.artifactDetail('root', 'artifact', undefined, 'cx/new')
    expect(fetcher.mock.calls[0]?.[0]).toBe('/api/phone-factory/collection-runs/root/artifacts/artifact?execution_id=cx%2Fnew')
    expect(phoneFactoryApi.artifactFileUrl('root', 'artifact', 'case/shot.jpg', 'cx/new')).toBe('/api/phone-factory/collection-runs/root/artifacts/artifact/file?path=case%2Fshot.jpg&execution_id=cx%2Fnew')
    expect(phoneFactoryApi.artifactFileUrl('root', 'artifact', 'old.jpg')).toBe('/api/phone-factory/collection-runs/root/artifacts/artifact/file?path=old.jpg')
  })
  it('retains a durable uncertain operation even when its HTTP 200 snapshot contains an error', async () => {
    const operation = { operation_id: 'stable', status: 'uncertain', error: 'collector timeout' }
    vi.stubGlobal('fetch', vi.fn(async () => new Response(JSON.stringify(operation))))
    expect(await phoneFactoryApi.resumeOperation('run', 'stable')).toEqual(operation)
  })
  it('requests production cancellation without mutating the evaluation endpoint', async () => {
    const fetcher = vi.fn(async () => new Response('{"status":"interrupted"}'))
    vi.stubGlobal('fetch', fetcher)
    await phoneFactoryApi.cancelCollection('cr/a')
    expect(fetcher.mock.calls[0]?.[0]).toBe('/api/phone-factory/collection-runs/cr%2Fa/cancel')
    expect(fetcher.mock.calls[0]?.[1]?.method).toBe('POST')
  })
  it('keeps the engine at the request top level and persists a separate default', async () => {
    const fetcher = vi.fn(async () => new Response('{"ok":true,"agent_types":{}}'))
    vi.stubGlobal('fetch', fetcher)
    const config = { sampling_enabled: true, temperature: 0.4, top_p: 0.8, use_experience_lib: false, capture_logprobs: true }
    await phoneFactoryApi.agentCapabilities()
    await phoneFactoryApi.saveConfig({ ...config, agent_type: 'pipelineagent' })
    await phoneFactoryApi.remoteStartRun({ filename: 'cases.xlsx', request_id: 'pipeline-one', vla: 'vla:8000', agent_type: 'pipelineagent', config })
    expect(fetcher.mock.calls[0]?.[0]).toBe('/api/phone-factory/agent-capabilities')
    expect(JSON.parse(String(fetcher.mock.calls[1]?.[1]?.body)).agent_type).toBe('pipelineagent')
    const request = JSON.parse(String(fetcher.mock.calls[2]?.[1]?.body))
    expect(request.agent_type).toBe('pipelineagent')
    expect(request.config).toEqual(config)
    expect(request.config).not.toHaveProperty('agent_type')
  })
  it('saves logprob defaults and sends an explicit per-run override without changing sampling', async () => {
    const fetcher = vi.fn(async () => new Response('{"ok":true}'))
    vi.stubGlobal('fetch', fetcher)
    const config = { sampling_enabled: true, temperature: 0.4, top_p: 0.8, use_experience_lib: false, capture_logprobs: true }
    await phoneFactoryApi.saveConfig(config)
    await phoneFactoryApi.remoteStartRun({ filename: 'manual.xlsx', request_id: 'capture-override', vla: 'vla:8000', config: { ...config, capture_logprobs: false } })
    expect(fetcher.mock.calls.map(call => call[0])).toEqual(['/api/phone-factory/config', '/api/phone-factory/remote/start-run'])
    expect(JSON.parse(String(fetcher.mock.calls[0]?.[1]?.body))).toEqual(config)
    expect(JSON.parse(String(fetcher.mock.calls[1]?.[1]?.body)).config).toEqual({ ...config, capture_logprobs: false })
    expect(config.capture_logprobs).toBe(true)
  })
  it('passes an explicit manual upload request ID without changing generated batch import identity', async () => {
    const fetcher = vi.fn(async () => new Response('{"tasks":[]}'))
    vi.stubGlobal('fetch', fetcher)
    await phoneFactoryApi.addTask('manual', 'same.xlsx', 'Ynl0ZXM=', undefined, 'upload-one')
    await phoneFactoryApi.addTask('batch', 'collection-batch-a.xlsx', 'Ynl0ZXM=', 'a')
    expect(JSON.parse(String(fetcher.mock.calls[0]?.[1]?.body))).toEqual({ description: 'manual', filename: 'same.xlsx', content_base64: 'Ynl0ZXM=', request_id: 'upload-one' })
    expect(JSON.parse(String(fetcher.mock.calls[1]?.[1]?.body))).toEqual({ description: 'batch', filename: 'collection-batch-a.xlsx', content_base64: 'Ynl0ZXM=', source_batch_id: 'a' })
  })

  it('keeps evaluation requests separate and passes run configuration with caller idempotency', async () => {
    const fetcher = vi.fn(async () => new Response(JSON.stringify({ ok: true, runs: [], folders: [] })))
    vi.stubGlobal('fetch', fetcher)
    const options = { filename: 'manual.xlsx', phone_id: 'phone-1', app: 'App', request_id: 'same-request', vla: 'vla:8000', run_mode: 'modeliter' as const, config: { sampling_enabled: true, temperature: 0.4, top_p: 0.8, use_experience_lib: false, capture_logprobs: false } }
    await modelIterationApi.remoteStartRun(options); await modelIterationApi.runs(); await modelIterationApi.reports()
    expect(fetcher.mock.calls.map(call => call[0])).toEqual(['/api/model-iter/remote/start-run', '/api/model-iter/runs', '/api/model-iter/reports'])
    expect(JSON.parse(String(fetcher.mock.calls[0]?.[1]?.body))).toEqual(options)
    await phoneFactoryApi.syncRun('cr/a')
    expect(fetcher.mock.calls.at(-1)?.[0]).toBe('/api/phone-factory/collection-runs/cr%2Fa/sync')
  })
  it('uses stable report identities and forwards polling cancellation', async () => {
    const fetcher = vi.fn(async () => new Response('{"ok":true,"devices":[]}'))
    vi.stubGlobal('fetch', fetcher)
    const controller = new AbortController()
    await phoneFactoryApi.adbDevices(controller.signal)
    expect(fetcher.mock.calls[0]?.[1]?.signal).toBe(controller.signal)
    await modelIterationApi.reportDownload({ index: 1, dir_name: 'old-folder', run_id: 'eval-1', files: [] }, { name: 'report.xlsx', file_id: 'file-1', size: 1 })
    expect(fetcher.mock.calls.at(-1)?.[0]).toBe('/api/model-iter/report-download?run_id=eval-1&file_id=file-1&name=report.xlsx')
  })
  it('isolates evaluator settings and preserves case result identities and cancellation', async () => {
    const fetcher = vi.fn(async () => new Response('{"ok":true}'))
    vi.stubGlobal('fetch', fetcher)
    const config = { text: { base_url: 'http://text/v1/', model: 'text', api_key_env: 'TEXT_KEY' }, vision: { base_url: 'http://vision/v1/', model: 'vision', api_key_env: 'VISION_KEY' } }
    await modelIterationApi.saveEvaluationConfig(config)
    const controller = new AbortController()
    await modelIterationApi.evaluations('eval/a', controller.signal)
    await modelIterationApi.evaluationCapabilities()
    expect(fetcher.mock.calls.map(call => call[0])).toEqual(['/api/model-iter/evaluation-config', '/api/model-iter/runs/eval%2Fa/evaluations', '/api/model-iter/evaluation-capabilities'])
    expect(fetcher.mock.calls[0]?.[1]?.method).toBe('PUT')
    expect(JSON.parse(String(fetcher.mock.calls[0]?.[1]?.body))).toEqual(config)
    expect(fetcher.mock.calls[1]?.[1]?.signal).toBe(controller.signal)
  })
  it('previews a server source and starts an independent evaluation without a phone or VLA', async () => {
    const fetcher = vi.fn(async () => new Response('{"ok":true,"preview_id":"preview-a","valid":true}'))
    vi.stubGlobal('fetch', fetcher)
    const controller = new AbortController()
    await modelIterationApi.evaluationProfiles(); await modelIterationApi.evaluationSources()
    await modelIterationApi.evaluationPreview({ source_run_id: 'source-a' }, controller.signal)
    await modelIterationApi.evaluationPreview({ source_path: 'D:/采集结果/batch-a' })
    const options = { request_id: 'reeval-one', evaluator_config: { text: { base_url: 'https://text/v1/', model: 'text', api_key_env: 'TEXT_KEY' }, vision: { base_url: 'https://vision/v1/', model: 'vision', api_key_env: 'VISION_KEY' } }, evaluation_profile_id: 'rules-v2', evaluation_profile_digest: 'sha-rules', preview_id: 'preview-a', checklist_source: 'auto' as const }
    await modelIterationApi.remoteStartEvaluation(options)
    await modelIterationApi.cancelEvaluation('eval/a')
    expect(fetcher.mock.calls.map(call => call[0])).toEqual(['/api/model-iter/evaluation-profiles', '/api/model-iter/evaluation-sources', '/api/model-iter/evaluation-preview', '/api/model-iter/evaluation-preview', '/api/model-iter/remote/start-evaluation', '/api/model-iter/runs/eval%2Fa/cancel'])
    expect(fetcher.mock.calls[2]?.[1]?.signal).toBe(controller.signal)
    expect(JSON.parse(String(fetcher.mock.calls[2]?.[1]?.body))).toEqual({ source_run_id: 'source-a' })
    expect(JSON.parse(String(fetcher.mock.calls[3]?.[1]?.body))).toEqual({ source_path: 'D:/采集结果/batch-a' })
    expect(JSON.parse(String(fetcher.mock.calls[4]?.[1]?.body))).toEqual(options)
  })
  it('passes the selected rule version on streaming evaluation starts without changing production parameters', async () => {
    const fetcher = vi.fn(async () => new Response('{"ok":true}'))
    vi.stubGlobal('fetch', fetcher)
    const options = { filename: 'cases.xlsx', vla: 'vla:8000', request_id: 'online-one', run_mode: 'modeliter' as const, evaluation_profile_id: 'v1', evaluation_profile_digest: 'hash', checklist_source: 'auto' as const }
    await modelIterationApi.remoteStartRun(options)
    expect(JSON.parse(String(fetcher.mock.calls[0]?.[1]?.body))).toEqual(options)
  })
  it('uses the evaluation transfer retry endpoint without starting another collection or evaluation', async () => {
    const fetcher = vi.fn(async () => new Response('{"run_id":"eval/a","status":"running","transfer_status":"waiting"}'))
    vi.stubGlobal('fetch', fetcher)
    await modelIterationApi.retryTransfer('eval/a')
    expect(fetcher.mock.calls).toHaveLength(1)
    expect(fetcher.mock.calls[0]?.[0]).toBe('/api/model-iter/runs/eval%2Fa/retry-transfer')
    expect(fetcher.mock.calls[0]?.[1]?.method).toBe('POST')
    expect(JSON.parse(String(fetcher.mock.calls[0]?.[1]?.body))).toEqual({})
  })
  it('keeps published task sources and run history visible while result writes remain separate', async () => {
    notifyBatchesPublished({ batch_ids: ['published-source-api'], release_id: 'release-old' })
    const fetcher = vi.fn(async () => new Response(JSON.stringify({ batches: [{ batch_id: 'published-source-api' }], runs: [] })))
    vi.stubGlobal('fetch', fetcher)
    expect(await factoryBatchesApi.list()).toEqual([{ batch_id: 'published-source-api' }])
    await factoryBatchesApi.list({ batch_role: 'collection_result', include_published: false })
    expect(fetcher.mock.calls[1]?.[0]).toBe('/api/phone-factory/batches?batch_role=collection_result&include_published=false')
    await phoneFactoryApi.runs()
    expect(fetcher.mock.calls[2]?.[0]).toBe('/api/phone-factory/collection-runs?include_published=true')
    await modelIterationApi.runs()
    expect(fetcher.mock.calls[3]?.[0]).toBe('/api/model-iter/runs')
  })

  it('queries the unified batch source and reports remote deletion failure', async () => {
    const fetcher = vi.fn(async () => new Response('{"batches":[]}'))
    vi.stubGlobal('fetch', fetcher)
    await factoryBatchesApi.list()
    expect(fetcher.mock.calls[0]?.[0]).toBe('/api/phone-factory/batches?batch_role=source&include_published=true')
    fetcher.mockResolvedValueOnce(new Response('{"ok":false,"error":"device stop failed"}'))
    await expect(phoneFactoryApi.remoteDeletePhone('phone-1')).rejects.toThrow('device stop failed')
    expect(fetcher.mock.calls).toHaveLength(2)
  })
})
